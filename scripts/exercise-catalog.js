// Rebuilds src/lib/exercise-catalog.ts from the public-domain (Unlicense)
// free-exercise-db: https://github.com/yuhonas/free-exercise-db
//
// The AI program builder may only add exercises that have a photo; this is the
// list it picks new ones from. Photos load from the repo and are saved with the
// program. Run with `node scripts/exercise-catalog.js`.
const fs = require('node:fs');
const path = require('node:path');

const SOURCE =
  'https://raw.githubusercontent.com/yuhonas/free-exercise-db/main/dist/exercises.json';
const OUT = path.resolve(__dirname, '..', 'src', 'lib', 'exercise-catalog.ts');

// Stretching, strongman and olympic lifts don't belong in a regular program.
const CATEGORIES = new Set(['strength', 'cardio', 'plyometrics', 'powerlifting']);

const GROUPS = {
  chest: 'chest',
  lats: 'back',
  'middle back': 'back',
  'lower back': 'back',
  traps: 'back',
  quadriceps: 'legs',
  hamstrings: 'legs',
  glutes: 'legs',
  calves: 'legs',
  adductors: 'legs',
  abductors: 'legs',
  shoulders: 'shoulders',
  neck: 'shoulders',
  biceps: 'biceps',
  forearms: 'biceps',
  triceps: 'triceps',
  abdominals: 'abs',
};

// Matches the equipment answers in src/lib/program-ai.ts; 'gym' needs a full gym.
const EQUIPMENT = {
  dumbbell: 'dumbbells',
  barbell: 'barbell',
  'e-z curl bar': 'barbell',
  kettlebells: 'kettlebell',
  bands: 'bands',
  'body only': 'bodyweight',
};

async function main() {
  const res = await fetch(SOURCE);
  if (!res.ok) throw new Error(`${SOURCE}: ${res.status}`);
  const all = await res.json();
  const rows = all
    .filter((e) => CATEGORIES.has(e.category) && e.level !== 'expert' && e.images.length > 0)
    .map((e) => [
      e.name.trim(),
      e.images[0],
      e.category === 'cardio' ? 'cardio' : (GROUPS[e.primaryMuscles[0]] ?? 'abs'),
      EQUIPMENT[e.equipment] ?? (e.equipment ? 'gym' : 'bodyweight'),
      e.category === 'plyometrics' ? 1 : 0,
    ])
    .sort((a, b) => a[0].localeCompare(b[0]));

  // Single-quoted like the rest of the code.
  const quote = (v) =>
    typeof v === 'string' ? `'${v.replace(/\\/g, '\\\\').replace(/'/g, "\\'")}'` : String(v);
  const body = rows.map((r) => `  [${r.map(quote).join(', ')}],`).join('\n');
  fs.writeFileSync(
    OUT,
    `// Generated by scripts/exercise-catalog.js from the public-domain free-exercise-db.
// Do not edit by hand.
import type { MuscleGroup } from '@/db/schema';

/** name, photo path in the repo, muscle group, equipment answer ('gym' = full gym only), jumps */
export type CatalogRow = [string, string, MuscleGroup, string, 0 | 1];

export const EXERCISE_CATALOG: CatalogRow[] = [
${body}
];
`,
  );
  console.log(`${rows.length} exercises -> ${path.relative(process.cwd(), OUT)}`);
}

main().catch((e) => {
  console.error(e);
  process.exit(1);
});
