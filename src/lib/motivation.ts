/** Phrase for the local calendar day of `date`. */
export function dailyPhrase(date: Date) {
  const day = Math.floor(
    Date.UTC(date.getFullYear(), date.getMonth(), date.getDate()) / 86_400_000,
  );
  return PHRASES[day % PHRASES.length];
}
